/**
 * Linearly interpolate between two SVG path strings.
 * Extracts all numbers from both paths, interpolates each pair by t,
 * and returns the reconstructed path string.
 */
export function lerpPath(
  basePath: string,
  trainedPath: string,
  t: number
): string {
  const baseNums = basePath.match(/-?\d+\.?\d*/g)?.map(Number) ?? [];
  const trainedNums = trainedPath.match(/-?\d+\.?\d*/g)?.map(Number) ?? [];
  if (baseNums.length !== trainedNums.length) return basePath;

  let idx = 0;
  return basePath.replace(/-?\d+\.?\d*/g, () => {
    const result = baseNums[idx] + (trainedNums[idx] - baseNums[idx]) * t;
    idx++;
    return result.toFixed(1);
  });
}

