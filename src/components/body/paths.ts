// SVG bezier path data for front and back body views
// Coordinate space: 200 wide x 400 tall. Center at x=100. Head top y=10, feet y=390.
//
// Each region carries four path variants:
//   lean    — 10 % body fat, untrained
//   base    — 20 % body fat, untrained
//   fat     — 30 % body fat, untrained
//   trained — any BF %, fully developed muscle
//
// At render time we:
//   1. Lerp lean → base → fat based on bodyFatPercent  (two-segment lerp)
//   2. Lerp the result toward `trained` by muscleSize
// This means a 25 % BF powerlifter looks noticeably different from a
// 25 % BF couch potato.

export interface BodyRegion {
  id: string;
  muscle: string;
  lean: string;    // 10 % BF, untrained
  base: string;    // 20 % BF, untrained
  fat: string;     // 30 % BF, untrained
  trained: string; // any BF %, fully trained muscles
}

// ---------------------------------------------------------------------------
// Path interpolation
// ---------------------------------------------------------------------------

/**
 * Linearly interpolate between two SVG path strings.
 * Extracts every number from both paths, lerps each pair by t,
 * and reconstructs the path string.
 */
export function lerpPath(a: string, b: string, t: number): string {
  const aN = a.match(/-?\d+\.?\d*/g)?.map(Number) ?? [];
  const bN = b.match(/-?\d+\.?\d*/g)?.map(Number) ?? [];
  if (aN.length !== bN.length) return a;
  let idx = 0;
  return a.replace(/-?\d+\.?\d*/g, () => {
    const v = aN[idx] + (bN[idx] - aN[idx]) * t;
    idx++;
    return v.toFixed(1);
  });
}

function clamp(v: number, lo: number, hi: number): number {
  return Math.min(hi, Math.max(lo, v));
}

/**
 * Compute the final SVG path for a region given body fat % and muscle size.
 *
 *   bfT = clamp((bodyFatPercent - 10) / 20, 0, 1)   → 0 at 10 %, 0.5 at 20 %, 1 at 30 %
 *
 * Two-segment lerp:
 *   bfT <= 0.5 → lean → base  (t = bfT * 2)
 *   bfT >  0.5 → base → fat   (t = (bfT - 0.5) * 2)
 *
 * Then lerp toward trained by muscleSize (0-1).
 */
export function getRegionPath(
  region: BodyRegion,
  bodyFatPercent: number,
  muscleSize: number,
): string {
  const bfT = clamp((bodyFatPercent - 10) / 20, 0, 1);

  let bfPath: string;
  if (bfT <= 0.5) {
    bfPath = lerpPath(region.lean, region.base, bfT * 2);
  } else {
    bfPath = lerpPath(region.base, region.fat, (bfT - 0.5) * 2);
  }

  if (muscleSize <= 0) return bfPath;
  return lerpPath(bfPath, region.trained, clamp(muscleSize, 0, 1));
}

